package com.peoplehub.account

import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.ClearCredentialException
import androidx.credentials.exceptions.GetCredentialException
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException
import com.peoplehub.R

/**
 * "Sign in with Google" through Credential Manager: the account every read and write goes through.
 *
 * The ID token is requested for the project's web client (`default_web_client_id`, generated by the
 * google-services plugin from `app/google-services.json`), which is what Firebase Auth accepts. The
 * Android OAuth client behind it is matched on the package name and the signing certificate's SHA-1,
 * so a build signed with a key not registered in Firebase gets no token.
 */
internal object GoogleSignIn {
    /** Shows the Google account picker; [activityContext] must be an Activity context. */
    suspend fun requestIdToken(activityContext: Context): Result<String> {
        val option =
            GetSignInWithGoogleOption
                .Builder(serverClientId = activityContext.getString(R.string.default_web_client_id))
                .build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        return try {
            val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                Result.success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                Result.failure(IllegalStateException("Unexpected credential type ${credential.type}"))
            }
        } catch (e: GetCredentialException) {
            Result.failure(e)
        } catch (e: GoogleIdTokenParsingException) {
            Result.failure(e)
        }
    }

    /** Forgets the account chosen last time, so the next sign-in shows the picker again. */
    suspend fun clear(context: Context) {
        try {
            CredentialManager.create(context).clearCredentialState(ClearCredentialStateRequest())
        } catch (_: ClearCredentialException) {
            // Nothing cached to clear: signing out of Firebase already happened.
        }
    }
}
