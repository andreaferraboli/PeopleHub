package com.peoplehub.core.database.sync

import androidx.sqlite.db.SupportSQLiteDatabase
import com.peoplehub.core.database.sync.SyncCollections.CHECK_INS
import com.peoplehub.core.database.sync.SyncCollections.EVENTS
import com.peoplehub.core.database.sync.SyncCollections.PEOPLE
import com.peoplehub.core.database.sync.SyncCollections.REMINDERS
import com.peoplehub.core.database.sync.SyncCollections.REMINDER_COMPLETIONS

/**
 * The SQL that feeds `sync_outbox`, in one place so the v10 -> v11 migration and a freshly created
 * database (the `onCreate` / destructive-migration callback) install exactly the same triggers.
 *
 * Every insert, update and delete on a synced table records "this document changed now" in the
 * outbox, unless `sync_state.applying_remote` is set: that is the sync engine applying a change that
 * came *from* the cloud, which must not be queued to go back up. Tags and interests are part of the
 * person document, so their triggers mark the owning person (and quietly do nothing when the person
 * itself is being deleted, since its own trigger already queued the tombstone).
 *
 * Foreign-key cascades fire triggers too, so deleting a person queues tombstones for their check-ins,
 * reminders and completion log, and unlinks their events, with no extra code.
 *
 * Two more triggers keep `check_in.outing_remote_id` filled: app code never sets it, and the trigger
 * copies it from a sibling row of the same `outing_id`, or draws a new UUID for a new outing.
 */
object SyncTriggers {
    /** A random v4 UUID in canonical lowercase 8-4-4-4-12 form, generated by SQLite. */
    const val UUID_SQL: String =
        "(lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || " +
            "substr(lower(hex(randomblob(2))), 2) || '-' || substr('89ab', 1 + (abs(random()) % 4), 1) || " +
            "substr(lower(hex(randomblob(2))), 2) || '-' || lower(hex(randomblob(6))))"

    /** The device clock in epoch milliseconds, as SQLite sees it. */
    private const val NOW_MILLIS = "CAST((julianday('now') - 2440587.5) * 86400000 AS INTEGER)"

    private const val NOT_APPLYING_REMOTE =
        "(SELECT applying_remote FROM sync_state WHERE id = 1) IS NOT 1"

    /** Every statement, in order. Each one is idempotent (`IF NOT EXISTS` / `OR IGNORE`). */
    val statements: List<String> =
        buildList {
            add("INSERT OR IGNORE INTO sync_state (id, applying_remote) VALUES (1, 0)")
            addAll(rowTriggers("person", PEOPLE))
            addAll(childOfPersonTriggers("person_tag"))
            addAll(childOfPersonTriggers("interest"))
            addAll(rowTriggers("check_in", CHECK_INS))
            addAll(rowTriggers("event", EVENTS, updatedColumns = "title, date_time_epoch_millis, description, category, person_id"))
            addAll(rowTriggers("reminder", REMINDERS))
            addAll(rowTriggers("reminder_completion", REMINDER_COMPLETIONS))
            addAll(outingIdentityTriggers())
        }

    /** Installs the triggers (and the `sync_state` row) on [db]. */
    fun install(db: SupportSQLiteDatabase) {
        statements.forEach(db::execSQL)
    }

    private fun enqueue(collection: String, remoteId: String): String =
        "INSERT OR REPLACE INTO sync_outbox (collection, remote_id, changed_at) " +
            "VALUES ('$collection', $remoteId, $NOW_MILLIS);"

    /**
     * Insert, update and delete triggers that queue the row's own document. [updatedColumns] limits
     * the update trigger to the columns that are part of the document (events keep their background
     * image and widget pin on the phone, so changing those must not push anything).
     */
    private fun rowTriggers(table: String, collection: String, updatedColumns: String? = null): List<String> {
        val updateOf = updatedColumns?.let { " OF $it" }.orEmpty()
        return listOf(
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_ai AFTER INSERT ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${enqueue(collection, "NEW.remote_id")} END",
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_au AFTER UPDATE$updateOf ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${enqueue(collection, "NEW.remote_id")} END",
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_ad AFTER DELETE ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${enqueue(collection, "OLD.remote_id")} END",
        )
    }

    /** Triggers on a person's child table (tags, interests) that queue the owning person's document. */
    private fun childOfPersonTriggers(table: String): List<String> {
        fun markPerson(ref: String) =
            "INSERT OR REPLACE INTO sync_outbox (collection, remote_id, changed_at) " +
                "SELECT '$PEOPLE', remote_id, $NOW_MILLIS FROM person WHERE id = $ref.person_id;"
        return listOf(
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_ai AFTER INSERT ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${markPerson("NEW")} END",
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_au AFTER UPDATE ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${markPerson("NEW")} END",
            "CREATE TRIGGER IF NOT EXISTS sync_${table}_ad AFTER DELETE ON $table " +
                "WHEN $NOT_APPLYING_REMOTE BEGIN ${markPerson("OLD")} END",
        )
    }

    /**
     * Fills `check_in.outing_remote_id` whenever a row is written without one: the id of any other
     * row of the same outing, or a new UUID when the row starts (or was detached into) a new outing.
     */
    private fun outingIdentityTriggers(): List<String> {
        val fill =
            "UPDATE check_in SET outing_remote_id = COALESCE(" +
                "(SELECT c.outing_remote_id FROM check_in c WHERE c.outing_id = NEW.outing_id " +
                "AND c.id <> NEW.id AND c.outing_remote_id IS NOT NULL LIMIT 1), $UUID_SQL) " +
                "WHERE id = NEW.id;"
        return listOf(
            "CREATE TRIGGER IF NOT EXISTS sync_check_in_outing_ai AFTER INSERT ON check_in " +
                "WHEN NEW.outing_remote_id IS NULL BEGIN $fill END",
            "CREATE TRIGGER IF NOT EXISTS sync_check_in_outing_au AFTER UPDATE OF outing_id, outing_remote_id ON check_in " +
                "WHEN NEW.outing_remote_id IS NULL BEGIN $fill END",
        )
    }
}
