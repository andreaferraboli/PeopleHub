/**
 * The 3D objects of the Velluto heroes, one per tab, as VectorDrawables generated by
 * `tools/scenes/build_scenes.py` from the mockups. They are placeholders meant to be swapped for
 * real renders: replace the drawable, keep the enum.
 *
 * @property width rendered size, as in the mockup.
 * @property baseRotation resting tilt in degrees.
 * @property swing extra tilt reached at the top of the float (degrees, signed).
 * @property lift how far the object rises at the top of the float.
 */
enum class SceneArt(
    @DrawableRes val drawable: Int,
    val width: Dp,
    val height: Dp,
    val baseRotation: Float,
    val swing: Float,
    val lift: Dp,
) {
    /** Two interlocked gold rings: La Cerchia. */
    Rings(R.drawable.scene_rings, 180.dp, 135.dp, -14f, 6f, 10.dp),

    /** Isometric gift box with ribbon: Riflessione (birthdays). */
    Gift(R.drawable.scene_gift, 160.dp, 160.dp, -9f, 4f, 11.dp),

    /** Push pin: Cronologia (events). */
    Pin(R.drawable.scene_pin, 104.dp, 146.dp, 24f, -6f, 10.dp),

    /** Gold-framed hourglass: Promemoria. */
    Hourglass(R.drawable.scene_hourglass, 112.dp, 144.dp, 14f, -5f, 10.dp),

    /** Padlock with dial: La Cassaforte. */
    Lock(R.drawable.scene_lock, 176.dp, 196.dp, 12f, -5f, 12.dp),
}

private const val SHADOW_MIN_SCALE = 0.82f
private const val SHADOW_MAX_ALPHA = 0.55f
private const val SHADOW_MIN_ALPHA = 0.35f
private const val GLOW_SIZE_RATIO = 0.7f

/**
 * A 3D object floating in place: it bobs up by [SceneArt.lift] and tilts by [SceneArt.swing] over
 * 6.5 s, over an accent glow ([glow]) and a ground shadow that shrinks as it rises ([groundShadow]).
 * Decorative: no semantics. Still when animations are off.
 */
@Composable
fun FloatingScene(
    art: SceneArt,
    modifier: Modifier = Modifier,
    glow: Boolean = true,
    groundShadow: Boolean = true,
    delayMillis: Int = 0,
) {
    val c = PeopleHubTheme.colors
    val motion = PeopleHubTheme.motion
    val pulse = rememberPulse(motion.reduced, motion.floatMillis, delayMillis)
    Box(modifier = modifier.size(art.width, art.height + 16.dp)) {
        if (glow) {
            AmbientGlow(
                size = art.width * GLOW_SIZE_RATIO,
                strong = true,
                color = c.glowStrong,
                modifier = Modifier.align(Alignment.Center),
            )
        }
        if (groundShadow) {
            Box(
                modifier =
                    Modifier
                        .align(Alignment.BottomCenter)
                        .requiredSize(art.width * GLOW_SIZE_RATIO, 16.dp)
                        .graphicsLayer {
                            val p = pulse?.value ?: 0f
                            val s = 1f - (1f - SHADOW_MIN_SCALE) * p
                            scaleX = s
                            scaleY = s
                            alpha = SHADOW_MAX_ALPHA - (SHADOW_MAX_ALPHA - SHADOW_MIN_ALPHA) * p
                        }.radialGlow(c.dropShadow),
            )
        }
        Image(
            painter = painterResource(art.drawable),
            contentDescription = null,
            modifier =
                Modifier
                    .align(Alignment.TopCenter)
                    .size(art.width, art.height)
                    .graphicsLayer {
                        val p = pulse?.value ?: 0f
                        translationY = -art.lift.toPx() * p
                        rotationZ = art.baseRotation + art.swing * p
                    },
        )
    }
}

/**
 * Illustrated covers for events without a background photo, generated from the Eventi mockup.
 * Placeholders for real photos: the user's own photo always wins.
 */
enum class CoverScene(
    @DrawableRes val drawable: Int,
) {
    Travel(R.drawable.scene_cover_travel),
    Milestone(R.drawable.scene_cover_milestone),
    Dinner(R.drawable.scene_cover_dinner),
    Wedding(R.drawable.scene_cover_wedding),
    Anniversary(R.drawable.scene_cover_anniversary),
    Home(R.drawable.scene_cover_home),
}

/** Keyword hints (Italian and English stems) that pick a fitting cover for a free-form category. */
private val CoverHints: List<Pair<CoverScene, List<String>>> =
    listOf(
        CoverScene.Travel to listOf("viagg", "travel", "trip", "vacan", "weekend", "volo", "flight"),
        CoverScene.Milestone to listOf("laure", "gradu", "tragu", "milestone", "promo", "lavoro", "job", "esame", "exam"),
        CoverScene.Dinner to listOf("cena", "dinner", "pranzo", "lunch", "aperit", "festa", "party", "gala"),
        CoverScene.Wedding to listOf("matrimon", "wedding", "spos", "nozze", "marri"),
        CoverScene.Anniversary to listOf("anniver", "fidanz", "amore", "love", "coppia"),
        CoverScene.Home to listOf("casa", "home", "house", "trasloc", "move", "chiavi", "keys"),
    )

/**
 * Picks the [CoverScene] for an event: by keyword in its [category] (then [title]) when one matches,
 * otherwise a stable pick from the title's hash so every event keeps its own cover.
 */
fun coverSceneFor(
    category: String?,
    title: String,
): CoverScene {
    val haystacks = listOfNotNull(category, title).map { it.lowercase(Locale.ROOT) }
    haystacks.forEach { text ->
        CoverHints.firstOrNull { (_, stems) -> stems.any { it in text } }?.let { return it.first }
    }
    val all = CoverScene.entries
    return all[Math.floorMod(title.hashCode(), all.size)]
}
